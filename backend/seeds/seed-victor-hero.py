def main():
    media_dir = Path(settings.MEDIA_ROOT) / 'players'
    media_dir.mkdir(parents=True, exist_ok=True)
    target = media_dir / 'victor-u15-05.jpg'
    data = base64.b64decode(''.join(B64))

    wrote = False
    if (not target.exists()) or target.stat().st_size != len(data):
        target.write_bytes(data)
        wrote = True

    p = Player.objects.filter(ref=REF).first()
    if p is None:
        print(f'seed-victor-hero: roster has no player {REF} - '
              'skipped (non-fatal)')
        return 0

    current = (getattr(p.photo, 'name', '') or '').strip()
    if current == REL and not wrote:
        print(f'seed-victor-hero: already applied ({REL})')
        return 0

    p.photo.name = REL
    p.save(update_fields=['photo'])
    print(f'seed-victor-hero: {"wrote photo file; " if wrote else ""}'
          f'linked {REF} {p.first_name} {p.last_name} -> {REL}')
    return 0


